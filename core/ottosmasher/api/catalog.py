"""导出命令目录与前端类型（ROADMAP L2）。

``python -m ottosmasher.api.catalog``          写 ``docs/api/commands.json`` 与 ``app/renderer/api/generated.ts``
``python -m ottosmasher.api.catalog --check``  只比较，不一致退出码 1（测试也做同样的比较）

前端类型由 JSON Schema 转写（同一份产物）：对象 → interface，``bytes``（msgpack 二进制）→ ``Uint8Array``，整数与小数 → ``number``。
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

import msgspec

from ..core.errors import table as error_table
from .registry import CommandSet

ROOT = Path(__file__).resolve().parents[3]
JSON_PATH = ROOT / "docs" / "api" / "commands.json"
TS_PATH = ROOT / "app" / "renderer" / "api" / "generated.ts"
CATALOG_VERSION = 1


def default_commands() -> CommandSet:
    """不打开工作区、只为读取登记表而构造 Core（处理函数不会被调用）。"""
    from ..core.server import Core

    return Core(Path("unused-workspace")).api


def build(commands: CommandSet) -> dict[str, Any]:
    cmds = sorted(commands, key=lambda c: c.name)
    types: list[Any] = []
    for c in cmds:
        types += [c.params, c.result]
    schemas, defs = msgspec.json.schema_components(types, ref_template="#/$defs/{name}")
    out = []
    for i, c in enumerate(cmds):
        out.append({"name": c.name, "effect": c.effect, "summary": c.summary, "params": schemas[2 * i], "result": schemas[2 * i + 1]})
    return {"catalogVersion": CATALOG_VERSION, "commands": out, "errors": error_table(), "$defs": dict(sorted(defs.items()))}


# ---------------------------------------------------------------- JSON Schema → TypeScript

_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _paren(t: str) -> str:
    return f"({t})" if (" | " in t or " & " in t) else t


def ts_type(s: Any) -> str:
    if s is True or s == {}:
        return "unknown"
    if "$ref" in s:
        return _ref_name(s["$ref"])
    if "anyOf" in s:
        parts: list[str] = []
        for x in s["anyOf"]:
            t = ts_type(x)
            if t not in parts:
                parts.append(t)
        return " | ".join(parts)
    if "enum" in s:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in s["enum"])
    if "const" in s:
        return json.dumps(s["const"], ensure_ascii=False)
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**s, "type": x}) for x in t)
    if t == "string":
        return "Uint8Array" if s.get("contentEncoding") == "base64" else "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(ts_type(x) for x in s["prefixItems"]) + "]"
        return _paren(ts_type(s.get("items", {}))) + "[]"
    if t == "object":
        if "properties" in s:
            return _object_body(s, indent="")
        ap = s.get("additionalProperties")
        return f"Record<string, {ts_type(ap) if isinstance(ap, dict) else 'unknown'}>"
    return "unknown"


def _prop_name(name: str) -> str:
    return name if _IDENT.match(name) else json.dumps(name, ensure_ascii=False)


def _object_body(s: dict[str, Any], indent: str) -> str:
    req = set(s.get("required", []))
    props = s.get("properties", {})
    if not props:
        return "{}"
    lines = [f"{indent}  {_prop_name(k)}{'' if k in req else '?'}: {ts_type(v)};" for k, v in props.items()]
    return "{\n" + "\n".join(lines) + f"\n{indent}}}"


def _doc(text: str | None, indent: str = "") -> str:
    if not text:
        return ""
    body = text.strip().replace("*/", "*\\/").splitlines()
    if len(body) == 1:
        return f"{indent}/** {body[0]} */\n"
    return f"{indent}/**\n" + "".join(f"{indent} * {ln}\n" if ln else f"{indent} *\n" for ln in body) + f"{indent} */\n"


def render_ts(cat: dict[str, Any]) -> str:
    out = [
        "// Generated by `python -m ottosmasher.api.catalog` - do not edit.",
        "// Source of truth: core/ottosmasher/api/types.py and the command registrations in core/ottosmasher/core/server.py.",
        "/* eslint-disable */",
        "",
    ]
    for name, s in cat["$defs"].items():
        out.append(_doc(s.get("description")) + f"export interface {name} {_object_body(s, '')}\n")
    out.append("/** All Core commands: params, result and effect. */")
    out.append("export interface Commands {")
    for c in cat["commands"]:
        out.append(_doc(c["summary"], "  ") + f'  "{c["name"]}": {{ params: {ts_type(c["params"])}; result: {ts_type(c["result"])}; effect: "{c["effect"]}" }};')
    out.append("}")
    out.append("")
    out.append("export type CommandName = keyof Commands;")
    out.append("")
    out.append("/** Core error codes (argument names: docs/api/commands.json, errors). */")
    out.append("export type ErrorCode =\n" + "\n".join(f'  | "{e["code"]}"' for e in cat["errors"]) + ";")
    out.append("")
    return "\n".join(out)


def render_json(cat: dict[str, Any]) -> str:
    return json.dumps(cat, ensure_ascii=False, indent=1) + "\n"


def outputs(commands: CommandSet | None = None) -> dict[Path, str]:
    cat = build(commands or default_commands())
    return {JSON_PATH: render_json(cat), TS_PATH: render_ts(cat)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="ottosmasher.api.catalog")
    ap.add_argument("--check", action="store_true", help="compare only; exit 1 if generated files are stale")
    args = ap.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        cur = path.read_text(encoding="utf-8") if path.exists() else None
        if cur == text:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    for p in stale:
        print(("stale: " if args.check else "wrote: ") + str(p.relative_to(ROOT)))
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
